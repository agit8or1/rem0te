/**
 * The standard Linux agent (0.32): a POSIX sh script run every three minutes
 * by a systemd timer, installed by the Linux installer (PublicController
 * buildLinuxScript) and embedded in it verbatim.
 *
 * It does what the Windows standard agent's heartbeat does, minus everything
 * that acts on the machine:
 *
 *   - heartbeats to /enrollment/heartbeat with the device secret the installer
 *     bound at claim (the same claim flow Windows uses — no new mechanism);
 *   - when the response hands it an INVENTORY_REFRESH or UPDATE_SCAN command,
 *     collects and posts the result to /enrollment/command-result, exactly as
 *     heartbeat.ps1 does;
 *   - answers an EVENT_LOG_QUERY with a failure (there is no Windows event log),
 *     so a staged query is closed out rather than retried until it expires.
 *
 * **It is read-only.** It parses exactly two things out of the response — a
 * command id matching a fixed charset and one of three fixed type names — and
 * ignores everything else: `rotate`, `updateRustdesk`, `reinstallAgent`,
 * `monitor`, `diagnostics`, `actions`. There is no `eval`, no `.`/`source`, no
 * `sh -c`, no download and no package-manager command that changes anything;
 * pending updates are read with `apt list --upgradable` (never `apt update`),
 * `dnf -C check-update` and `zypper --no-refresh list-updates`.
 * scripts/check-security-invariants.mjs §24 asserts all of that against the
 * text below.
 *
 * Everything it sends is reduced on the device before it leaves — printable
 * ASCII without `"` or `\`, clamped to the heartbeat DTO's lengths — and the
 * server sanitises it again (enrollment.service deviceText, and the
 * inventory sanitisers). /etc/os-release is read with sed, never sourced.
 *
 * The template is String.raw so shell backslashes survive untouched, which is
 * why the script never uses the `${…}` parameter-expansion form: in a template
 * literal that would be an interpolation. `__AGENT_VERSION__` is the only
 * substitution.
 *
 * Test overrides (REM0TE_AGENT_CONF, REM0TE_AGENT_SECRET_FILE,
 * REM0TE_RUSTDESK_CONFIG, REM0TE_OS_RELEASE, REM0TE_DMI_DIR, and TMPDIR) only
 * change where it reads from, so apps/api/scripts/e2e-linux-agent.mjs can run
 * the generated script unprivileged inside a temp directory.
 */

const VERSION_RE = /^[a-zA-Z0-9._+-]{1,32}$/;

export const LINUX_AGENT_PATH = '/usr/local/lib/rem0te/rem0te-agent';
export const LINUX_AGENT_CONF = '/etc/rem0te-agent.conf';
export const LINUX_AGENT_SECRET = '/etc/rem0te-agent.secret';
/** The heredoc delimiter the installer embeds the agent with. */
export const LINUX_AGENT_HEREDOC = 'REM0TE_AGENT_EOF';

export function buildLinuxAgentScript(agentVersion: string): string {
  const v = VERSION_RE.test(agentVersion) ? agentVersion : 'unknown';
  if (LINUX_AGENT_TEMPLATE.includes('${')) throw new Error('linux agent template must not contain ${');
  return LINUX_AGENT_TEMPLATE.replace(/__AGENT_VERSION__/g, v);
}

/** systemd units. Read-only filesystem for /usr and /etc while it runs. */
export const LINUX_AGENT_SERVICE = `[Unit]
Description=Rem0te agent (standard, read-only): heartbeat and inventory
Documentation=https://github.com/agit8or1/rem0te/blob/main/docs/inventory.md
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
ExecStart=/bin/sh ${LINUX_AGENT_PATH}
TimeoutStartSec=300
Nice=10
# The agent only reads. These make the operating system hold it to that for
# the parts of the filesystem that matter; /var stays writable because apt,
# dnf and zypper keep their caches and locks there even for a read.
ProtectSystem=full
ProtectHome=read-only
PrivateTmp=yes
NoNewPrivileges=yes
ProtectKernelTunables=yes
ProtectControlGroups=yes
RestrictSUIDSGID=yes
`;

export const LINUX_AGENT_TIMER = `[Unit]
Description=Rem0te agent heartbeat, every three minutes

[Timer]
OnBootSec=2min
OnUnitActiveSec=3min
RandomizedDelaySec=20s
AccuracySec=15s

[Install]
WantedBy=timers.target
`;

const LINUX_AGENT_TEMPLATE = String.raw`#!/bin/sh
# Rem0te agent for Linux (standard, read-only). Generated by the Rem0te server,
# platform version __AGENT_VERSION__. Run by rem0te-agent.timer every 3 minutes.
#
# It reports this computer to Rem0te and never acts on what Rem0te says: the
# heartbeat response is searched for command ids and three fixed command
# names, and nothing else in it is read. Remove it with the installer's
# --uninstall, or see docs/inventory.md ("Removing the Linux agent").
umask 077
LC_ALL=C
export LC_ALL
# PATH is systemd's standard one (or sudo's secure_path for a manual run).

AGENT_VERSION='__AGENT_VERSION__'
CONF=/etc/rem0te-agent.conf
SECRET_FILE=/etc/rem0te-agent.secret
RD_CONFIGS='/root/.config/rustdesk/RustDesk.toml /root/.config/rustdesk/RustDesk2.toml /var/lib/rustdesk/RustDesk.toml /var/lib/rustdesk/RustDesk2.toml'
OS_RELEASE=/etc/os-release
DMI_DIR=/sys/class/dmi/id
if [ -n "$REM0TE_AGENT_CONF" ]; then CONF=$REM0TE_AGENT_CONF; fi
if [ -n "$REM0TE_AGENT_SECRET_FILE" ]; then SECRET_FILE=$REM0TE_AGENT_SECRET_FILE; fi
if [ -n "$REM0TE_RUSTDESK_CONFIG" ]; then RD_CONFIGS=$REM0TE_RUSTDESK_CONFIG; fi
if [ -n "$REM0TE_OS_RELEASE" ]; then OS_RELEASE=$REM0TE_OS_RELEASE; fi
if [ -n "$REM0TE_DMI_DIR" ]; then DMI_DIR=$REM0TE_DMI_DIR; fi

log() { printf 'rem0te-agent: %s\n' "$*" >&2; }

# ---- Reducing what leaves this machine --------------------------------------
# Printable ASCII only, without the two characters that would end or escape a
# JSON string, clamped to $2 bytes. Every string in every request goes through
# txt or nm, which is why no JSON escaping is needed anywhere below.
txt() { printf '%s' "$1" | tr -cd ' -~' | tr -d '"\\' | cut -c1-"$2"; }
# Names (host names): the inert charset the Connect script also reduces to.
nm() { printf '%s' "$1" | tr -cd 'A-Za-z0-9._-' | cut -c1-"$2"; }
isnum() { case "$1" in ''|*[!0-9]*) return 1;; esac; return 0; }

# ---- Configuration: read with sed, never sourced ----------------------------
conf_get() { sed -n "s/^$1=//p" "$CONF" 2>/dev/null | head -n 1; }
API_BASE=$(conf_get API_BASE)
if ! printf '%s' "$API_BASE" | grep -Eq '^https://[A-Za-z0-9.-]+(:[0-9]{1,5})?/api/v1$'; then
  # Plain http only to this machine itself: the test suite's scratch API.
  if ! printf '%s' "$API_BASE" | grep -Eq '^http://(127\.0\.0\.1|localhost)(:[0-9]{1,5})?/api/v1$'; then
    log "API_BASE in $CONF is missing or not an https URL; re-run the installer"
    exit 1
  fi
fi

# ---- The device secret ------------------------------------------------------
# Written by the installer and bound to this computer by the claim. Without it
# the server takes nothing this agent says, so it does not try.
if [ ! -f "$SECRET_FILE" ]; then
  log "no device secret at $SECRET_FILE; re-run the installer from an enrolment link"
  exit 1
fi
mode=$(stat -c %a "$SECRET_FILE" 2>/dev/null)
case "$mode" in
  600|400) ;;
  *) log "refusing to use $SECRET_FILE: mode $mode, it must be 600 (readable by root only)"; exit 1;;
esac
SECRET=$(tr -cd 'A-Za-z0-9_-' < "$SECRET_FILE" | cut -c1-128)
if [ "$(printf '%s' "$SECRET" | wc -c)" -lt 16 ]; then
  log "the device secret in $SECRET_FILE is unreadable or too short"
  exit 1
fi

# ---- Identity ---------------------------------------------------------------
RID=''
for f in $RD_CONFIGS; do
  [ -r "$f" ] || continue
  RID=$(sed -n "s/^[[:space:]]*id[[:space:]]*=[[:space:]]*['\"]\([0-9]\{6,15\}\)['\"].*/\1/p" "$f" 2>/dev/null | head -n 1)
  [ -n "$RID" ] && break
done
if [ -z "$RID" ]; then
  log "RustDesk has no ID yet (looked in: $RD_CONFIGS); nothing to report as"
  exit 0
fi

TMPD=$(mktemp -d 2>/dev/null) || { log "cannot create a temporary directory"; exit 1; }
trap 'rm -rf "$TMPD"' EXIT
trap 'exit 1' INT TERM

# POST the body in $2 to $1. The body goes through a file in the private
# temporary directory, never argv: argv is visible to every user on the
# machine through ps, and the body carries the secret. Not on a pipe either —
# the right side of a pipe is a subshell, and CODE would be lost.
post() {
  printf '%s' "$2" > "$TMPD/req"
  CODE=$(curl -sS --max-time 60 --max-redirs 0 -o "$TMPD/resp" -w '%{http_code}' \
    -H 'Content-Type: application/json' --data-binary @"$TMPD/req" "$API_BASE$1" 2>"$TMPD/curl.err")
  rm -f "$TMPD/req"
  [ -n "$CODE" ] || CODE=000
}

# ---- Live state (every heartbeat) -------------------------------------------
host=$(hostname -s 2>/dev/null) || host=''
[ -n "$host" ] || host=$(uname -n 2>/dev/null)
host=$(nm "$(printf '%s' "$host" | cut -d. -f1)" 64)

osr_get() { sed -n "s/^$1=//p" "$OS_RELEASE" 2>/dev/null | head -n 1 | sed -e 's/^"//' -e 's/"$//' -e "s/^'//" -e "s/'$//"; }
os_name=$(osr_get PRETTY_NAME)
[ -n "$os_name" ] || os_name="$(osr_get NAME) $(osr_get VERSION)"
os_name=$(txt "$os_name" 64)
kernel=$(txt "$(uname -r 2>/dev/null)" 64)
arch=$(txt "$(uname -m 2>/dev/null)" 32)

uptime_s=$(cut -d' ' -f1 /proc/uptime 2>/dev/null | cut -d. -f1)
isnum "$uptime_s" || uptime_s=''
boot_at=''
btime=$(awk '/^btime /{print $2; exit}' /proc/stat 2>/dev/null)
if isnum "$btime"; then boot_at=$(date -u -d "@$btime" '+%Y-%m-%dT%H:%M:%SZ' 2>/dev/null) || boot_at=''; fi
boot_at=$(txt "$boot_at" 32)

# Processor busy share over one second, from the kernel's own counters
# (iowait counted as idle). Not the load average, which is not a percentage.
cpu_sample() { awk '/^cpu /{t=0; for (i=2; i<=NF; i++) t+=$i; printf "%.0f %.0f\n", t, $5+$6; exit}' /proc/stat 2>/dev/null; }
s1=$(cpu_sample); sleep 1; s2=$(cpu_sample)
cpu=$(printf '%s %s\n' "$s1" "$s2" | awk 'NF==4 {dt=$3-$1; di=$4-$2; if (dt>0) {p=100*(dt-di)/dt; if (p<0) p=0; if (p>100) p=100; printf "%.0f", p}}')
isnum "$cpu" || cpu=''

mem=$(awk '/^MemTotal:/{t=$2} /^MemAvailable:/{a=$2} /^MemFree:/{f=$2} /^Buffers:/{b=$2} /^Cached:/{c=$2}
  END {if (a=="") a=f+b+c; if (t>0) printf "%.0f %.0f", t/1024, a/1024}' /proc/meminfo 2>/dev/null)
mem_total=$(printf '%s' "$mem" | cut -d' ' -f1); isnum "$mem_total" || mem_total=''
mem_free=$(printf '%s' "$mem" | cut -s -d' ' -f2); isnum "$mem_free" || mem_free=''

root_df=$(df -Pk / 2>/dev/null | awk 'NR==2 {printf "%.0f %.0f", $2/1024, $4/1024}')
disk_total=$(printf '%s' "$root_df" | cut -d' ' -f1); isnum "$disk_total" || disk_total=''
disk_free=$(printf '%s' "$root_df" | cut -s -d' ' -f2); isnum "$disk_free" || disk_free=''

# Everyone with a login session, console or remote, as who(1) lists them. An
# empty string means nobody; the field is left out when who is not there.
users=''
have_who=0
if command -v who >/dev/null 2>&1; then
  have_who=1
  users=$(who 2>/dev/null | awk '{u=$1; gsub(/[^A-Za-z0-9._@-]/, "", u); if (u != "" && !(u in s)) {s[u]=1; printf "%s%s", (n++ ? ", " : ""), u}}')
  users=$(txt "$users" 128)
fi

# The installed RustDesk package's version, asked of the package database.
rdv=''
if command -v dpkg-query >/dev/null 2>&1; then rdv=$(dpkg-query -W rustdesk 2>/dev/null | awk '{print $2; exit}'); fi
if [ -z "$rdv" ] && command -v rpm >/dev/null 2>&1; then rdv=$(rpm -q --qf '%{VERSION}' rustdesk 2>/dev/null); fi
rdv=$(printf '%s' "$rdv" | grep -oE '^[0-9]+\.[0-9]+\.[0-9]+' | head -n 1)

body="{\"rustdeskId\":\"$RID\",\"agentSecret\":\"$SECRET\",\"platform\":\"linux\",\"agentVersion\":\"$(txt "$AGENT_VERSION" 32)\""
[ -n "$host" ] && body="$body,\"hostname\":\"$host\""
[ -n "$os_name" ] && body="$body,\"osVersion\":\"$os_name\""
[ -n "$rdv" ] && body="$body,\"rustdeskVersion\":\"$rdv\""
[ "$have_who" = 1 ] && body="$body,\"loggedOnUser\":\"$users\""
[ -n "$uptime_s" ] && body="$body,\"uptimeSeconds\":$uptime_s"
[ -n "$boot_at" ] && body="$body,\"lastBootAt\":\"$boot_at\""
[ -n "$cpu" ] && body="$body,\"cpuLoadPercent\":$cpu"
[ -n "$mem_total" ] && body="$body,\"memoryTotalMb\":$mem_total"
[ -n "$mem_free" ] && body="$body,\"memoryFreeMb\":$mem_free"
[ -n "$disk_total" ] && body="$body,\"systemDiskTotalMb\":$disk_total"
[ -n "$disk_free" ] && body="$body,\"systemDiskFreeMb\":$disk_free"
body="$body}"

post /enrollment/heartbeat "$body"
case "$CODE" in
  200) ;;
  401) log "heartbeat refused (HTTP 401): the server does not hold this computer's device secret. Re-run the installer from an enrolment link made for it."; exit 0;;
  *) log "heartbeat failed (HTTP $CODE) $(head -c 300 "$TMPD/curl.err" 2>/dev/null)"; exit 0;;
esac
resp=$(cat "$TMPD/resp" 2>/dev/null)
case "$resp" in
  *'"authenticated":true'*) ;;
  *) log "heartbeat recorded as liveness only: this computer's device secret is not bound on the server"; exit 0;;
esac

# ---- Collections ------------------------------------------------------------
dmi() { [ -r "$DMI_DIR/$1" ] && txt "$(head -n 1 "$DMI_DIR/$1" 2>/dev/null)" "$2"; }
jstr() { [ -n "$2" ] && printf ',"%s":"%s"' "$1" "$2"; }
jnum() { isnum "$2" && printf ',"%s":%s' "$1" "$2"; }

chassis_name() {
  case "$1" in
    3) echo Desktop;; 4) echo 'Low Profile Desktop';; 5) echo 'Pizza Box';; 6) echo 'Mini Tower';; 7) echo Tower;;
    8) echo Portable;; 9) echo Laptop;; 10) echo Notebook;; 11) echo Handheld;; 12) echo 'Docking Station';;
    13) echo 'All In One';; 14) echo 'Sub Notebook';; 15) echo 'Space Saving';; 17) echo Server;; 23) echo 'Rack Mount';;
    30) echo Tablet;; 31) echo Convertible;; 32) echo Detachable;; '') ;; *) isnum "$1" && echo "Type $1";;
  esac
}

disks_json() {
  if out=$(df -PkT 2>/dev/null); then typed=1; else out=$(df -Pk 2>/dev/null); typed=0; fi
  printf '%s\n' "$out" | awk -v typed="$typed" '
    NR == 1 { next }
    {
      if (typed) { dev=$1; t=$2; tot=$3; av=$5; first=7 } else { dev=$1; t=""; tot=$2; av=$4; first=6 }
      if (t ~ /^(tmpfs|devtmpfs|squashfs|overlay|proc|sysfs|cgroup2?|efivarfs|ramfs|nsfs|tracefs|autofs|debugfs|securityfs|pstore|bpf|configfs|fusectl|mqueue|hugetlbfs|devpts|binfmt_misc|fuse\..*)$/) next
      if (dev in seen) next
      seen[dev] = 1
      m = $first; for (i = first + 1; i <= NF; i++) m = m " " $i
      gsub(/[^ -~]/, "", m); gsub(/["\\]/, "", m); gsub(/[^ -~]/, "", dev); gsub(/["\\]/, "", dev); gsub(/[^A-Za-z0-9._-]/, "", t)
      if (n >= 32 || m == "") next
      printf "%s{\"drive\":\"%s\",\"label\":\"%s\",\"fsType\":\"%s\",\"totalBytes\":%.0f,\"freeBytes\":%.0f}", (n++ ? "," : ""), substr(m, 1, 16), substr(dev, 1, 64), substr(t, 1, 32), tot * 1024, av * 1024
    }'
}

inventory_json() {
  cpu_model=$(awk -F': *' '/^model name/ {print $2; exit}' /proc/cpuinfo 2>/dev/null)
  [ -n "$cpu_model" ] || cpu_model=$(awk -F': *' '/^(Model|Hardware)[[:space:]]*:/ {print $2; exit}' /proc/cpuinfo 2>/dev/null)
  threads=$(grep -c '^processor' /proc/cpuinfo 2>/dev/null)
  isnum "$threads" && [ "$threads" -gt 0 ] || threads=$(nproc 2>/dev/null)
  cores=$(awk -F': *' '/^physical id/ {p=$2} /^core id/ {c[p ":" $2]=1} END {n=0; for (k in c) n++; if (n>0) print n}' /proc/cpuinfo 2>/dev/null)
  mhz=''
  if [ -r /sys/devices/system/cpu/cpu0/cpufreq/cpuinfo_max_freq ]; then
    mhz=$(awk '{printf "%.0f", $1/1000; exit}' /sys/devices/system/cpu/cpu0/cpufreq/cpuinfo_max_freq 2>/dev/null)
  fi
  [ -n "$mhz" ] || mhz=$(awk -F': *' '/^cpu MHz/ {printf "%.0f", $2; exit}' /proc/cpuinfo 2>/dev/null)
  tz=$(readlink /etc/localtime 2>/dev/null | sed -n 's#.*/zoneinfo/##p')
  [ -n "$tz" ] || tz=$(head -n 1 /etc/timezone 2>/dev/null)
  bios_date=$(dmi bios_date 16 | awk -F/ 'NF==3 && $3 ~ /^[0-9]{4}$/ {printf "%s-%s-%sT00:00:00Z", $3, $1, $2}')
  printf '{"osCaption":"%s"' "$os_name"
  jstr osBuild "$kernel"; jstr osArch "$arch"; jstr timezone "$(txt "$tz" 64)"
  jstr manufacturer "$(dmi sys_vendor 128)"; jstr model "$(dmi product_name 128)"
  jstr serialNumber "$(dmi product_serial 128)"; jstr chassisType "$(chassis_name "$(dmi chassis_type 4)")"
  jstr biosVersion "$(dmi bios_version 128)"; jstr biosDate "$bios_date"
  jstr cpuModel "$(txt "$cpu_model" 128)"; jnum cpuCores "$cores"; jnum cpuThreads "$threads"; jnum cpuMhz "$mhz"
  jnum memoryTotalMb "$mem_total"; jnum memoryFreeMb "$mem_free"
  printf ',"disks":[%s]}' "$(disks_json)"
}

# Pending package updates, read from what the package manager already knows.
# Nothing here refreshes a repository or changes a package: apt's list is as
# of the last "apt update" on this computer, dnf runs from its cache (-C) and
# zypper with --no-refresh. With none of the three, the answer is unknown and
# the command is reported as failed with that reason, never as "no updates".
UPD_ERR=''
MGR=''
updates_list() {
  if command -v apt >/dev/null 2>&1 && command -v dpkg >/dev/null 2>&1; then
    MGR=apt
    out=$(apt list --upgradable 2>/dev/null) || { UPD_ERR='apt list --upgradable failed'; return 1; }
    printf '%s\n' "$out" | awk '/\[upgradable from: / {
      split($1, a, "/"); old = $NF; sub(/\]$/, "", old)
      sev = (a[2] ~ /-security/) ? "Security" : ""
      print a[1] " " $2 " (installed " old ")\t" sev }'
    return 0
  fi
  if command -v dnf >/dev/null 2>&1; then
    MGR=dnf
    out=$(dnf -q -C check-update 2>/dev/null); rc=$?
    case "$rc" in
      0) return 0;;
      100) ;;
      *) UPD_ERR="dnf check-update (from cache) failed with status $rc; the metadata cache may be empty (dnf-makecache.timer fills it)"; return 1;;
    esac
    # Long names wrap onto a second line, so fields are gathered three at a
    # time rather than read one line each. Obsoletes are not updates.
    printf '%s\n' "$out" | awk '/^Obsoleting/ {exit} /^Security:/ {next} { for (i = 1; i <= NF; i++) { f[++k] = $i; if (k == 3) { n = f[1]; sub(/\.[^.]*$/, "", n); print n " " f[2] "\t"; k = 0 } } }'
    return 0
  fi
  if command -v zypper >/dev/null 2>&1; then
    MGR=zypper
    out=$(zypper --non-interactive --no-refresh list-updates 2>/dev/null) || { UPD_ERR='zypper list-updates --no-refresh failed; zypper may be busy'; return 1; }
    printf '%s\n' "$out" | awk -F'|' '$1 ~ /^[[:space:]]*v[[:space:]]*$/ && NF >= 6 {
      for (i = 1; i <= NF; i++) gsub(/^[[:space:]]+|[[:space:]]+$/, "", $i)
      print $3 " " $5 " (installed " $4 ")\t" }'
    return 0
  fi
  UPD_ERR='Pending updates unknown: none of apt, dnf or zypper is on this computer'
  return 1
}

# Restart pending, asked the way the package manager in use records it.
# Prints nothing (unknown) rather than guess.
reboot_flag() {
  case "$MGR" in
    apt)
      if [ -e /run/reboot-required ] || [ -e /var/run/reboot-required ]; then echo true
      # No flag file is evidence only where the hook that writes it is installed.
      elif [ -e /usr/share/update-notifier/notify-reboot-required ]; then echo false; fi;;
    dnf)
      if command -v needs-restarting >/dev/null 2>&1; then
        needs-restarting -r >/dev/null 2>&1
        case $? in 0) echo false;; 1) echo true;; esac
      fi;;
    zypper)
      zypper --non-interactive needs-rebooting >/dev/null 2>&1
      case $? in 0) echo false;; 102) echo true;; esac;;
  esac
}

# Writes the updates object to stdout. Never called inside $( ): UPD_ERR has
# to survive, and a command substitution is a subshell.
updates_json() {
  updates_list > "$TMPD/upd.list" || return 1
  tab=$(printf '\t')
  items=$(head -n 100 "$TMPD/upd.list" | while IFS=$tab read -r title sev; do
    [ -n "$title" ] || continue
    printf ',{"title":"%s"' "$(txt "$title" 300)"
    [ -n "$sev" ] && printf ',"severity":"%s"' "$(txt "$sev" 32)"
    printf '}'
  done)
  items=$(printf '%s' "$items" | sed 's/^,//')
  rb=$(reboot_flag)
  printf '{"pending":[%s]' "$items"
  case "$rb" in true|false) printf ',"rebootRequired":%s' "$rb";; esac
  printf '}'
}

result() { # id ok extra error
  r="{\"rustdeskId\":\"$RID\",\"agentSecret\":\"$SECRET\",\"commandId\":\"$1\",\"ok\":$2"
  [ -n "$3" ] && r="$r,$3"
  [ -n "$4" ] && r="$r,\"error\":\"$(txt "$4" 1000)\""
  post /enrollment/command-result "$r}"
  [ "$CODE" = 200 ] || log "command result for $1 not accepted (HTTP $CODE)"
}

# The only thing read from the response: command ids in a fixed charset and
# three fixed type names. A forged match could at worst make this agent
# describe the machine again.
printf '%s' "$resp" | grep -oE '\{"id":"[A-Za-z0-9_-]{1,64}","type":"(INVENTORY_REFRESH|UPDATE_SCAN|EVENT_LOG_QUERY)"' \
  | sed -E 's/^\{"id":"([A-Za-z0-9_-]+)","type":"([A-Z_]+)"$/\1 \2/' | head -n 4 > "$TMPD/cmds"
ran=0
# Read on fd 3, so nothing a collection runs can swallow the list from stdin.
while read -r cid ctype <&3; do
  case "$ctype" in
    INVENTORY_REFRESH) result "$cid" true "\"inventory\":$(inventory_json)" '';;
    UPDATE_SCAN)
      if updates_json > "$TMPD/upd.json"; then result "$cid" true "\"updates\":$(cat "$TMPD/upd.json")" ''
      else result "$cid" false '' "$UPD_ERR"; fi;;
    EVENT_LOG_QUERY) result "$cid" false '' 'Event logs are Windows-only: the Linux agent does not read logs.';;
  esac
  ran=$((ran + 1))
done 3< "$TMPD/cmds"
log "heartbeat ok; $ran command(s) answered"
exit 0
`;
