import { assemblePosixAgent, POSIX_AGENT_HEREDOC, POSIX_COMMANDS, POSIX_HEARTBEAT, POSIX_SETUP, POSIX_TRANSPORT } from './posix-agent';

/**
 * The standard macOS agent (0.33): a POSIX sh script run every three minutes
 * by a launchd LaunchDaemon, installed by the macOS installer (PublicController
 * buildMacosScript) when it runs as root, and embedded in it verbatim.
 *
 * It is the Linux agent (0.32) with macOS's ways of measuring the machine.
 * Everything that touches the device secret, the server or the server's
 * response is shared with Linux in posix-agent.ts: the same heartbeat, the
 * same claim-bound secret (no first-sight binding), the same three command
 * names, the same "read-only, acts on nothing the server sends".
 *
 * What is macOS about it:
 *
 *   - OS from `sw_vers`; kernel from `uname -r`; boot time from
 *     `sysctl kern.boottime`, converted in awk (BSD and GNU `date` disagree);
 *   - CPU busy share from `top -l 2` (the second sample: the first is since
 *     boot); memory from `sysctl hw.memsize` and `vm_stat`; disks from `df`
 *     and `mount`; the console user from `who`;
 *   - the RustDesk version from the app bundle's Info.plist, read with sed
 *     (`plutil -convert xml1 -o -`, to stdout, only if it is binary);
 *   - model and serial from `ioreg` (one registry class, depth 1), and the
 *     marketing name and firmware from `system_profiler SPHardwareDataType`,
 *     bounded to SP_TIMEOUT seconds and on the 6-hour inventory pass only;
 *   - pending updates from what macOS itself last found — see updates_list —
 *     never from running `softwareupdate`.
 *
 * Paths: everything under /Library/Rem0te (root:wheel 0755), never
 * /usr/local, which Homebrew makes writable by an admin user on Intel Macs —
 * a root daemon running a script from there could be replaced from that
 * account. PATH is fixed to the system directories for the same reason.
 *
 * Test overrides (REM0TE_AGENT_CONF, REM0TE_AGENT_SECRET_FILE,
 * REM0TE_RUSTDESK_CONFIG, REM0TE_RUSTDESK_APP, REM0TE_TEST_PATH and TMPDIR)
 * only change where it reads from and which commands it finds, so
 * apps/api/scripts/e2e-macos-agent.mjs can run the generated script
 * unprivileged, on Linux, against stubs of the macOS commands.
 */

export const MACOS_AGENT_DIR = '/Library/Rem0te';
export const MACOS_AGENT_PATH = `${MACOS_AGENT_DIR}/rem0te-agent`;
export const MACOS_AGENT_CONF = `${MACOS_AGENT_DIR}/agent.conf`;
export const MACOS_AGENT_SECRET = `${MACOS_AGENT_DIR}/agent.secret`;
export const MACOS_AGENT_LABEL = 'com.rem0te.agent';
export const MACOS_AGENT_PLIST = `/Library/LaunchDaemons/${MACOS_AGENT_LABEL}.plist`;
export const MACOS_AGENT_LOG = '/var/log/rem0te-agent.log';
export const MACOS_AGENT_NEWSYSLOG = '/etc/newsyslog.d/rem0te-agent.conf';
export const MACOS_AGENT_HEREDOC = POSIX_AGENT_HEREDOC;
/** The system directories only: no /usr/local (see above). */
const SYSTEM_PATH = '/usr/bin:/bin:/usr/sbin:/sbin';

export function buildMacosAgentScript(agentVersion: string): string {
  return assemblePosixAgent('macos', [
    MACOS_HEAD, POSIX_SETUP, MACOS_IDENTITY, POSIX_TRANSPORT, MACOS_LIVE, POSIX_HEARTBEAT, MACOS_COLLECT, POSIX_COMMANDS,
  ], agentVersion);
}

