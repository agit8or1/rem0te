import { Type } from 'class-transformer';
import { IsArray, IsBoolean, IsEnum, IsIn, IsInt, IsIP, IsISO8601, IsObject, IsOptional, IsString, Length, Matches, Max, MaxLength, Min, ArrayMaxSize } from 'class-validator';

export enum EndpointAccessMode {
  ASSIGNED_USERS = 'ASSIGNED_USERS',
  COMPANY_WIDE   = 'COMPANY_WIDE',
}

export class CreateClaimTokenDto {
  @IsOptional() @IsString() endpointId?: string;
  @IsOptional() @IsString() customerName?: string;
  @IsOptional() @IsString() siteName?: string;
  @IsOptional() @IsString() @Length(0, 256) description?: string;

  // Managed-computer enrollment binding. All of these travel WITH the token
  // (server-side) so the machine that redeems it cannot pick a different
  // business or assign itself to a different user.
  //
  // `businessId` is the current name; `customerId` is still accepted so a
  // client mid-upgrade keeps working.
  @IsOptional() @IsString() businessId?: string;
  @IsOptional() @IsString() customerId?: string;
  @IsOptional() @IsEnum(EndpointAccessMode) accessMode?: EndpointAccessMode;
  @IsOptional() @IsArray() @IsString({ each: true }) assignedUserIds?: string[];
  @IsOptional() @IsString() endpointGroupId?: string;
  // The site the device lands in. Must be an active site of the token's
  // business; checked at mint time and again at claim.
  @IsOptional() @IsString() @Length(1, 64) siteId?: string;
}

export class HeartbeatDto {
  @IsString()
  @Matches(/^[0-9]{6,15}$/, { message: 'rustdeskId must be numeric' })
  rustdeskId!: string;

  @IsOptional()
  @IsString()
  @Length(1, 64)
  hostname?: string;

  @IsOptional()
  @IsString()
  @Length(1, 32)
  platform?: string;

  @IsOptional()
  @IsString()
  @Length(1, 64)
  osVersion?: string;

  @IsOptional()
  @IsString()
  @Length(1, 32)
  agentVersion?: string;

  // Installed RustDesk client version, e.g. "1.4.9". Drives the update
  // check on the Updates page and clears a staged update once the endpoint
  // reports the target version.
  @IsOptional()
  @IsString()
  @Length(1, 32)
  rustdeskVersion?: string;

  @IsOptional()
  @IsIP()
  ipAddress?: string;

  // Optional permanent password from the on-device installer. Stored
  // encrypted on the RustdeskNode so that when a platform admin later
  // assigns an unassigned device to a tenant, the tenant already has
  // the password without needing the customer to re-type it.
  @IsOptional()
  @IsString()
  @Length(1, 128)
  password?: string;

  // Per-device secret generated by the installer. Proves the caller is the
  // machine it says it is; see RustdeskNode.agentSecretHash.
  @IsOptional()
  @IsString()
  @Length(16, 128)
  @Matches(/^[A-Za-z0-9_-]+$/, { message: 'agentSecret must be URL-safe base64' })
  agentSecret?: string;

  // Live session state. Cheap enough on the agent (one CIM query) to send on
  // every beat, and it is the first thing a technician looks at before
  // connecting: an empty string means nobody is signed in, which is different
  // from the field being absent.
  @IsOptional()
  @IsString()
  @Length(0, 128)
  loggedOnUser?: string;

  @IsOptional()
  @IsInt()
  @Min(0)
  uptimeSeconds?: number;

  @IsOptional()
  @IsISO8601()
  lastBootAt?: string;

  // Live resource sample. Sent every beat so the device page's gauges are
  // minutes old rather than hours; the slower inventory pass still carries
  // the full per-disk list and everything that does not move.
  @IsOptional() @IsInt() @Min(0) @Max(100) cpuLoadPercent?: number;
  @IsOptional() @IsInt() @Min(0) memoryTotalMb?: number;
  @IsOptional() @IsInt() @Min(0) memoryFreeMb?: number;
  @IsOptional() @IsInt() @Min(0) systemDiskTotalMb?: number;
  @IsOptional() @IsInt() @Min(0) systemDiskFreeMb?: number;

  // Incoming RustDesk sessions on this machine right now (count of
  // `rustdesk.exe --cm` connection-manager processes). Agents from 0.20.0.
  @IsOptional() @IsInt() @Min(0) @Max(64) rustdeskSessions?: number;
  // Set by the agent when the install it just ran was for a staged update,
  // echoing the nonce it was handed. See UpdateRolloutService.
  @IsOptional() @IsString() @Matches(/^[A-Za-z0-9_-]{16,64}$/) updateNonce?: string;
  // Signed update chain (0.24): which path this agent updates through, and the
  // signing root and targets versions it last verified. Agents before 0.24
  // send none of these and are treated as legacy.
  @IsOptional() @IsIn(['signed', 'legacy']) updateChannel?: 'signed' | 'legacy';
  @IsOptional() @IsInt() @Min(1) @Max(1_000_000) trustRootVersion?: number;
  @IsOptional() @IsInt() @Min(1) @Max(1_000_000_000) targetsVersion?: number;
  // Approved actions (0.26): the catalog actions the signed agent can execute
  // ("windows.service.start@1"), the digest of the agent build reporting them,
  // and the results of envelopes it was handed. Results are validated field by
  // field in ActionsService; the array itself is bounded here.
  @IsOptional() @IsArray() @ArrayMaxSize(16) @IsString({ each: true }) @Matches(/^[a-z0-9.]{3,64}@[0-9]{1,4}$/, { each: true }) agentActions?: string[];
  @IsOptional() @IsString() @Matches(/^[0-9a-f]{64}$/) agentSha256?: string;
  // @Type(() => Object): without it, enableImplicitConversion turns every
  // element of an untyped array into an empty array, and the results arrive
  // as [[]]. Validated element by element by ActionsService.recordResults.
  @IsOptional() @IsArray() @ArrayMaxSize(10) @Type(() => Object) actionResults?: unknown[];
  // Staged patching (0.27): the signed agent's patch-scan posture, validated
  // field by field in EndpointInventoryService.recordPatchPosture.
  @IsOptional() @IsObject() @Type(() => Object) patchPosture?: Record<string, unknown>;
  // Agent upgrade (0.34): lastCheck and lastResult from agent-status.json,
  // which the signed agent writes after every update (and a migrate run
  // writes on a standard machine). Display only; made inert server side.
  @IsOptional() @IsISO8601() agentUpdateCheckedAt?: string;
  @IsOptional() @IsString() @MaxLength(400) agentUpdateResult?: string;
  // Chat (0.34): the chat protocol the signed agent speaks, from its
  // agent-status.json. Stored only for a signed agent; it decides whether the
  // portal offers a chat, and the heartbeat says so only when one is open.
  @IsOptional() @IsInt() @Min(1) @Max(99) agentChat?: number;

  // The tray (0.36): the tray protocol this computer runs. Signed: from
  // agent-status.json. Standard: reported only once the tray is installed,
  // with the key id it was paired under (trayKeyId); the portal believes a
  // standard computer's tray only when that id is the one on record, and
  // otherwise answers `tray.pair` so the heartbeat pairs again.
  @IsOptional() @IsInt() @Min(1) @Max(99) agentTray?: number;
  @IsOptional() @IsString() @Matches(/^[a-z0-9]{24}$/) trayKeyId?: string;
}

/**
 * An endpoint reporting back on a command it was handed.
 *
 * Only one of `inventory` / `updates` / `events` is meaningful, decided by the
 * type of the command being closed out — the server picks the right one from
 * its own row rather than believing whichever field arrived. Each is validated
 * as a shape only; every value inside is clamped by
 * EndpointInventoryService's sanitisers, which is where the real bounds live.
 */
export class CommandResultDto {
  @IsString()
  @Matches(/^[0-9]{6,15}$/, { message: 'rustdeskId must be numeric' })
  rustdeskId!: string;

  @IsString()
  @Length(16, 128)
  @Matches(/^[A-Za-z0-9_-]+$/, { message: 'agentSecret must be URL-safe base64' })
  agentSecret!: string;

  @IsString()
  @Length(1, 64)
  commandId!: string;

  @IsBoolean()
  ok!: boolean;

  @IsOptional() @IsString() @Length(0, 2000) error?: string;
  @IsOptional() @IsObject() inventory?: Record<string, unknown>;
  @IsOptional() @IsObject() updates?: Record<string, unknown>;
  // @Type(() => Object): see actionResults above — without it every event
  // arrived as an empty array (fixed in 0.26.0).
  @IsOptional() @IsArray() @Type(() => Object) events?: unknown[];
}

/**
 * A monitor report (v0.29): the states of the services the heartbeat asked
 * about, and the match counts for its event queries. Bounded here, and
 * sanitised field by field — and only for services and event keys the
 * server actually asked for — in monitoring/engine.ts sanitizeReport.
 */
export class MonitorReportDto {
  @IsString()
  @Matches(/^[0-9]{6,15}$/, { message: 'rustdeskId must be numeric' })
  rustdeskId!: string;

  @IsString()
  @Length(16, 128)
  @Matches(/^[A-Za-z0-9_-]+$/, { message: 'agentSecret must be URL-safe base64' })
  agentSecret!: string;

  // @Type(() => Object): see actionResults above.
  @IsOptional() @IsArray() @ArrayMaxSize(64) @Type(() => Object) services?: unknown[];
  @IsOptional() @IsArray() @ArrayMaxSize(16) @Type(() => Object) events?: unknown[];
}

