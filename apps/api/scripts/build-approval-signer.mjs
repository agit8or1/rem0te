#!/usr/bin/env node
/**
 * Package the approval signer (v0.26) as its own install, apart from the
 * portal's.
 *
 *   cd apps/api && npx nest build
 *   node scripts/build-approval-signer.mjs --out /tmp/rem0te-approver
 *   (cd /tmp/rem0te-approver && npm install --omit=dev)          # must exit 0
 *   sudo rsync -a --delete /tmp/rem0te-approver/ /opt/rem0te-approver/
 *   sudo chown -R root:root /opt/rem0te-approver && sudo chmod -R go-w /opt/rem0te-approver
 *
 * Why a separate install: the portal's code lives in /opt/reboot-remote/api,
 * owned by the portal's own Unix user. If the signer ran from there, anyone
 * who took over the portal process could rewrite the signer's code and sign
 * whatever they liked with its key. Root-owned and read-only, the signer's
 * code is out of the portal's reach, the same as its key and roster.
 *
 * It copies exactly the files the signer loads, found by loading it (not by a
 * list someone has to keep in step), and refuses if that set ever reaches
 * outside approval-signer/, actions/catalog and integration/crypto — which is
 * how a Nest or Prisma import would announce itself. The manifest pins the
 * exact versions the API was built and tested against.
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync, existsSync, rmSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const apiRoot = path.join(here, '..');
const dist = path.join(apiRoot, 'dist');
const i = process.argv.indexOf('--out');
const out = i > 0 ? path.resolve(process.argv[i + 1]) : null;
const listOnly = process.argv.includes('--list');
if (!out && !listOnly) { console.error('usage: build-approval-signer.mjs --out DIR | --list'); process.exit(2); }

const ALLOWED = [/^approval-signer\//, /^actions\/catalog\.js$/, /^integration\/crypto\.js$/];
const DIRECT_DEPS = ['@simplewebauthn/server', 'zod'];

const require = createRequire(import.meta.url);
const before = new Set(Object.keys(require.cache));
for (const m of ['main.js', 'server.js', 'core.js', 'store.js', 'page.js']) {
  if (m === 'main.js') continue; // main.js runs a CLI on load; it imports only the four below
  require(path.join(dist, 'approval-signer', m));
}
const loaded = Object.keys(require.cache).filter((k) => !before.has(k));
const own = loaded.filter((k) => !k.includes(`${path.sep}node_modules${path.sep}`)).map((k) => path.relative(dist, k));
own.push('approval-signer/main.js');
const outside = own.filter((f) => !ALLOWED.some((re) => re.test(f)));
if (outside.length) { console.error(`the signer now loads files outside its allowed set: ${outside.join(', ')}`); process.exit(1); }
const modules = new Set(loaded.filter((k) => k.includes('node_modules')).map((k) => { const p = k.split(`node_modules${path.sep}`).pop().split(path.sep); return p[0].startsWith('@') ? `${p[0]}/${p[1]}` : p[0]; }));
for (const banned of ['@nestjs/core', '@nestjs/common', '@prisma/client', '.prisma', 'express']) {
  if (modules.has(banned)) { console.error(`the signer loads ${banned}; it must not`); process.exit(1); }
}
// main.js's own imports, checked by reading it: it must use only node built-ins and ./ files.
const mainSrc = readFileSync(path.join(dist, 'approval-signer', 'main.js'), 'utf8');
const mainReq = [...mainSrc.matchAll(/require\("([^"]+)"\)/g)].map((m) => m[1]);
const badMain = mainReq.filter((r) => !r.startsWith('node:') && !r.startsWith('./'));
if (badMain.length) { console.error(`main.js requires ${badMain.join(', ')}`); process.exit(1); }

if (listOnly) { console.log(own.sort().join('\n')); console.log(`modules: ${[...modules].sort().join(' ')}`); process.exit(0); }

const version = (name) => JSON.parse(readFileSync(path.join(apiRoot, 'node_modules', ...name.split('/'), 'package.json'), 'utf8')).version;
if (existsSync(out)) rmSync(out, { recursive: true, force: true });
for (const f of own) {
  mkdirSync(path.join(out, 'dist', path.dirname(f)), { recursive: true });
  copyFileSync(path.join(dist, f), path.join(out, 'dist', f));
}
const rootVersion = JSON.parse(readFileSync(path.join(apiRoot, '..', '..', 'version.json'), 'utf8')).version;
writeFileSync(path.join(out, 'package.json'), JSON.stringify({
  name: 'rem0te-approval-signer', version: rootVersion, private: true,
  description: 'rem0te approval signer — generated by apps/api/scripts/build-approval-signer.mjs; do not edit',
  license: 'UNLICENSED',
  dependencies: Object.fromEntries(DIRECT_DEPS.map((d) => [d, version(d)])),
}, null, 2) + '\n');
console.log(`wrote ${own.length} files and package.json (${DIRECT_DEPS.map((d) => `${d}@${version(d)}`).join(', ')}) to ${out}`);
